// Package clerk contains the Pulumi provider definition for Clerk.
//
// It uses pulumi-terraform-bridge (TPF path) to wrap the community
// buildwithdeck/terraform-provider-clerk Terraform provider v0.6.1. All
// resource and data source token mappings are declared explicitly below for
// clarity and auditability; MustComputeTokens fills in any gaps using standard
// naming.
package clerk

import (
	_ "embed"

	shim "github.com/buildwithdeck/terraform-provider-clerk/pulumi-bridge-shim"
	"github.com/pulumi/pulumi-clerk/provider/pkg/version"
	pf "github.com/pulumi/pulumi-terraform-bridge/v3/pkg/pf/tfbridge"
	"github.com/pulumi/pulumi-terraform-bridge/v3/pkg/tfbridge"
	"github.com/pulumi/pulumi-terraform-bridge/v3/pkg/tfbridge/tokens"
)

//go:embed cmd/pulumi-resource-clerk/bridge-metadata.json
var bridgeMetadata []byte

// Version is the provider version, sourced from the version package.
var Version = version.Version

// mainPkg is the short name of the Pulumi package.
const mainPkg = "clerk"

// mustSetVersion validates that the version placeholder is wired correctly and
// sets prov.Version. It panics at startup if the version string is empty, which
// catches the common mistake of forgetting to inject the build-time version via
// ldflags. The bridge's Version field is the surviving API post-v3.125.0;
// ProviderInfo.MustSetVersion was removed in that release.
func mustSetVersion(prov *tfbridge.ProviderInfo, v string) {
	if v == "" {
		panic("clerk provider version is empty -- check ldflags injection in cmd/pulumi-resource-clerk")
	}
	prov.Version = v
}

// Provider returns the ProviderInfo for the Clerk Pulumi provider.
//
// This is the top-level entry point used by both the provider resource server
// (cmd/pulumi-resource-clerk) and the schema generator (cmd/pulumi-tfgen-clerk).
func Provider() tfbridge.ProviderInfo {
	prov := tfbridge.ProviderInfo{
		// Wrap the upstream TPF provider via the shim.
		P: pf.ShimProvider(shim.NewProvider()),

		Name:        "clerk",
		DisplayName: "Clerk",
		Publisher:   "Pulumi",
		Description: "Pulumi provider for Clerk -- manage authentication, organizations, JWT templates, " +
			"SAML connections, and user management resources on the Clerk platform.",
		Keywords:          []string{"pulumi", "clerk", "auth", "authentication", "identity", "sso", "organizations"},
		License:           "Apache-2.0",
		Homepage:          "https://clerk.com",
		Repository:        "https://github.com/pulumi/autoregistry",
		PluginDownloadURL: "github://api.github.com/pulumi/autoregistry",

		// MetadataInfo embeds the bridge-metadata.json generated by make tfgen.
		// The empty placeholder ({}) is replaced with real content after the first run.
		MetadataInfo: tfbridge.NewProviderMetadata(bridgeMetadata),

		// Provider-level config: map upstream TF attribute names to env var defaults.
		Config: map[string]*tfbridge.SchemaInfo{
			"api_key": {
				Default: &tfbridge.DefaultInfo{
					EnvVars: []string{"CLERK_API_KEY"},
				},
			},
			"platform_api_key": {
				Default: &tfbridge.DefaultInfo{
					EnvVars: []string{"CLERK_PLATFORM_API_KEY"},
				},
			},
		},

		// Resources: explicit token declarations for all 20 upstream resources.
		Resources: map[string]*tfbridge.ResourceInfo{
			// Allowlist/blocklist controls
			"clerk_allowlist_identifier": {Tok: tfbridge.MakeResource(mainPkg, "index", "AllowlistIdentifier")},
			"clerk_blocklist_identifier": {Tok: tfbridge.MakeResource(mainPkg, "index", "BlocklistIdentifier")},
			// API & machine-to-machine tokens
			"clerk_api_key": {Tok: tfbridge.MakeResource(mainPkg, "index", "ApiKey")},
			"clerk_machine": {Tok: tfbridge.MakeResource(mainPkg, "index", "Machine")},
			// Application-level (Platform API beta)
			"clerk_application":          {Tok: tfbridge.MakeResource(mainPkg, "index", "Application")},
			"clerk_application_settings": {Tok: tfbridge.MakeResource(mainPkg, "index", "ApplicationSettings")},
			// Domain management (Platform API beta)
			"clerk_domain":          {Tok: tfbridge.MakeResource(mainPkg, "index", "Domain")},
			"clerk_instance_config": {Tok: tfbridge.MakeResource(mainPkg, "index", "InstanceConfig")},
			"clerk_instance_domain": {Tok: tfbridge.MakeResource(mainPkg, "index", "InstanceDomain")},
			// JWT templates
			"clerk_jwt_template": {Tok: tfbridge.MakeResource(mainPkg, "index", "JwtTemplate")},
			// OAuth
			"clerk_oauth_application": {Tok: tfbridge.MakeResource(mainPkg, "index", "OauthApplication")},
			// Organizations (B2B multi-tenancy)
			"clerk_organization":            {Tok: tfbridge.MakeResource(mainPkg, "index", "Organization")},
			"clerk_organization_domain":     {Tok: tfbridge.MakeResource(mainPkg, "index", "OrganizationDomain")},
			"clerk_organization_membership": {Tok: tfbridge.MakeResource(mainPkg, "index", "OrganizationMembership")},
			"clerk_organization_permission": {Tok: tfbridge.MakeResource(mainPkg, "index", "OrganizationPermission")},
			"clerk_organization_role":       {Tok: tfbridge.MakeResource(mainPkg, "index", "OrganizationRole")},
			"clerk_role_set":                {Tok: tfbridge.MakeResource(mainPkg, "index", "RoleSet")},
			// Redirect URL allowlist
			"clerk_redirect_url": {Tok: tfbridge.MakeResource(mainPkg, "index", "RedirectUrl")},
			// SAML / SSO
			"clerk_saml_connection": {Tok: tfbridge.MakeResource(mainPkg, "index", "SamlConnection")},
			// Webhooks via Svix
			"clerk_svix_webhook": {Tok: tfbridge.MakeResource(mainPkg, "index", "SvixWebhook")},
		},

		// DataSources: explicit token declarations for all 1 upstream data source.
		DataSources: map[string]*tfbridge.DataSourceInfo{
			// Lookup Clerk application metadata (Platform API beta).
			"clerk_application": {Tok: tfbridge.MakeDataSource(mainPkg, "index", "getApplication")},
		},

		// SDK language metadata.
		JavaScript: &tfbridge.JavaScriptInfo{
			PackageName: "@pulumi/clerk",
			Dependencies: map[string]string{
				"@pulumi/pulumi": "^3.0.0",
			},
			DevDependencies: map[string]string{
				"@types/node": "^18.0.0",
				"typescript":  "^5.0.0",
			},
		},
		Python: &tfbridge.PythonInfo{
			PackageName: "pulumi_clerk",
			Requires: map[string]string{
				"pulumi": ">=3.0.0,<4.0.0",
			},
		},
		Golang: &tfbridge.GolangInfo{
			ImportBasePath:                 "github.com/pulumi/pulumi-clerk/sdk/go/clerk",
			GenerateResourceContainerTypes: true,
		},
		CSharp: &tfbridge.CSharpInfo{
			RootNamespace: "Pulumi",
			PackageReferences: map[string]string{
				"Pulumi": "3.*",
			},
		},
		Java: &tfbridge.JavaInfo{
			BasePackage: "com.pulumi",
		},
	}

	// Auto-compute tokens for any resources/data sources not explicitly declared
	// above. SingleModule maps all clerk_* resources into the "index" module
	// using MakeStandard naming.
	prov.MustComputeTokens(tokens.SingleModule("clerk_", "index", tokens.MakeStandard(mainPkg)))

	// Validate that the provider version is set. mustSetVersion panics at startup
	// if the version string is empty, catching missing ldflags injection early.
	mustSetVersion(&prov, Version)

	return prov
}
